"""
Central configuration for paths and application settings.

All path references in the project resolve relative to the repository root
so that the application works regardless of where it is cloned.
"""

from pathlib import Path

# Repository root: the directory that contains this package.
ROOT = Path(__file__).resolve().parent.parent

# ── Data ──────────────────────────────────────────────────────────────────────
DATA_DIR = ROOT / "data"
CONTRIBUTION_CSV = DATA_DIR / "contribution.csv"
RECORD_LOG_CSV = DATA_DIR / "record_log.csv"

PRACTICE_DATA = {
    "intent": DATA_DIR / "practice_intent.csv",
    "sentiment": DATA_DIR / "practice_sentiment.csv",
    "semantic": DATA_DIR / "practice_semantic.csv",
}

# ── Artefacts (generated by train.py / evaluate.py) ──────────────────────────
ARTIFACTS_DIR = ROOT / "artifacts"


def artifact_dir(track: str) -> Path:
    """Return the artefact directory for a given track."""
    return ARTIFACTS_DIR / track


def model_path(track: str) -> Path:
    return artifact_dir(track) / "model.joblib"


def dev_metrics_path(track: str) -> Path:
    return artifact_dir(track) / "dev_metrics.json"


def test_metrics_path(track: str) -> Path:
    return artifact_dir(track) / "test_metrics.json"


def test_predictions_path(track: str) -> Path:
    return artifact_dir(track) / "test_predictions.csv"


def per_label_report_path(track: str) -> Path:
    return artifact_dir(track) / "per_label_report.csv"


# ── Supported tracks ─────────────────────────────────────────────────────────
SUPPORTED_TRACKS = ("intent", "sentiment", "semantic")

